import Link from "next/link";
import { connection } from "next/server";
import { Suspense } from "react";
import { isValidObjectId } from "mongoose";
import { LETTERS } from "@/lib/constants";
import { connectDB } from "@/lib/db";
import { Lecture, Question, Quiz } from "@/lib/models";
import { PublishButton, RemoveControls } from "./LectureControls";

export default function LecturePage({ params }: PageProps<"/admin/lectures/[lectureId]">) {
  return (
    <Suspense fallback={<p className="text-stone-500">Loading…</p>}>
      <LectureDetail params={params} />
    </Suspense>
  );
}

async function LectureDetail({ params }: { params: Promise<{ lectureId: string }> }) {
  await connection(); // database reads must happen at request time, not during prerendering
  const { lectureId } = await params;
  if (!isValidObjectId(lectureId)) return <p>Lecture not found.</p>;
  await connectDB();
  const [lecture, questions, quiz] = await Promise.all([
    Lecture.findById(lectureId, { text: 0 }).lean(),
    Question.find({ lectureId }).sort({ order: 1 }).lean(),
    Quiz.findOne({ lectureId }).lean(),
  ]);
  if (!lecture) return <p>Lecture not found.</p>;

  const active = questions.filter((q) => !q.removedBeforeSurvey);
  const locked = Boolean(quiz);
  const first = questions[0];

  return (
    <div>
      <Link href="/admin" className="text-sm text-stone-500 hover:underline">
        ← All lectures
      </Link>
      <div className="mt-2 flex flex-wrap items-start justify-between gap-4">
        <div className="min-w-0">
          <h1 className="text-2xl font-semibold">{lecture.title}</h1>
          <p className="mt-1 text-sm text-stone-500">
            {active.length} active · {questions.length - active.length} removed
            {first && (
              <>
                {" "}
                · generated by <span className="font-mono">{first.model}</span> on {new Date(first.generatedAt).toLocaleString()}
              </>
            )}
          </p>
        </div>
        {quiz ? (
          <Link href={`/admin/quiz/${quiz._id}`} className="btn-primary">
            View published survey →
          </Link>
        ) : (
          <PublishButton lectureId={lectureId} disabled={active.length === 0} count={active.length} />
        )}
      </div>

      {locked ? (
        <p className="mt-4 rounded-lg border border-stone-200 bg-stone-100 px-4 py-2.5 text-sm text-stone-700">
          This set has been published, so it is locked. Removals made before publishing are kept for the research record.
        </p>
      ) : (
        <p className="mt-4 rounded-lg border border-amber-200 bg-amber-50 px-4 py-2.5 text-sm text-amber-900">
          Review each question before publishing. Removed questions stay in the database with your reason, because removals are research data.
        </p>
      )}

      <ol className="mt-6 space-y-4">
        {questions.map((q, i) => (
          <li key={String(q._id)} className={`card ${q.removedBeforeSurvey ? "border-dashed bg-stone-50 opacity-75" : ""}`}>
            <div className="flex flex-wrap items-center gap-2 text-xs">
              <span className="font-semibold text-stone-500">Q{i + 1}</span>
              <span className="rounded-full bg-stone-100 px-2 py-0.5 text-stone-700 capitalize">{q.difficulty}</span>
              {!q.excerptFoundInText && (
                <span className="rounded-full bg-amber-100 px-2 py-0.5 text-amber-800" title="The excerpt was not found verbatim in the notes">
                  excerpt not verbatim
                </span>
              )}
              {q.removedBeforeSurvey && <span className="rounded-full bg-red-100 px-2 py-0.5 text-red-800">Removed</span>}
            </div>
            <p className={`mt-2 font-medium ${q.removedBeforeSurvey ? "line-through" : ""}`}>{q.question}</p>
            <ul className="mt-3 space-y-1.5 text-sm">
              {q.options.map((opt, j) => (
                <li
                  key={j}
                  className={`flex gap-2 rounded-md px-2.5 py-1.5 ${j === q.correctIndex ? "bg-emerald-50 font-medium text-emerald-900" : "text-stone-700"}`}
                >
                  <span className="w-4 shrink-0">{LETTERS[j]}.</span>
                  <span>{opt}</span>
                  {j === q.correctIndex && <span className="ml-auto shrink-0 text-xs">✓ correct</span>}
                </li>
              ))}
            </ul>
            <div className="mt-3 grid gap-3 text-sm md:grid-cols-2">
              <div>
                <p className="text-xs font-semibold tracking-wide text-stone-500 uppercase">Explanation</p>
                <p className="mt-1 text-stone-700">{q.explanation}</p>
              </div>
              <div>
                <p className="text-xs font-semibold tracking-wide text-stone-500 uppercase">Source excerpt</p>
                <blockquote className="mt-1 border-l-2 border-stone-300 pl-3 text-stone-600 italic">{q.sourceExcerpt}</blockquote>
              </div>
            </div>
            {q.removedBeforeSurvey && q.removalReason && (
              <p className="mt-3 text-sm text-red-800">
                <span className="font-medium">Removal reason:</span> {q.removalReason}
              </p>
            )}
            {!locked && <RemoveControls questionId={String(q._id)} removed={q.removedBeforeSurvey} />}
          </li>
        ))}
      </ol>
    </div>
  );
}
